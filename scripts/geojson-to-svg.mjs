#!/usr/bin/env node
/**
 * Converts a GeoJSON FeatureCollection of governorate boundaries into
 * src/data/geo/iraqGovernorates.js (SVG paths in one shared viewBox).
 *
 *   node scripts/geojson-to-svg.mjs boundaries.geojson \
 *     --name-property NAME_1 --source "Dataset name" --url "https://..." --license "CC BY 4.0" \
 *     [--out src/data/geo/iraqGovernorates.js] [--width 1000]
 *
 * It only reprojects what the file contains (equirectangular, scaled by cos(latitude)).
 * It never invents or edits geometry. Source and licence are REQUIRED so the map can credit them.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const input = args[0];
const opt = (name, fallback = '') => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : fallback;
};

const nameProperty = opt('name-property');
const source = opt('source');
const url = opt('url');
const license = opt('license');
const out = opt('out', 'src/data/geo/iraqGovernorates.js');
const width = Number(opt('width', '1000'));

if (!input || !nameProperty || !source || !license) {
  console.error('Usage: node scripts/geojson-to-svg.mjs <file.geojson> --name-property <PROP> --source "<name>" --license "<licence>" [--url <url>]');
  process.exit(1);
}

const geojson = JSON.parse(readFileSync(input, 'utf8'));
const features = geojson.type === 'FeatureCollection' ? geojson.features : [geojson];

const polygonsOf = (geometry) => {
  if (!geometry) return [];
  if (geometry.type === 'Polygon') return [geometry.coordinates];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates;
  return [];
};

let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
for (const f of features) for (const polygon of polygonsOf(f.geometry)) for (const ring of polygon) for (const [lon, lat] of ring) {
  minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
  minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
}
if (!Number.isFinite(minLon)) {
  console.error('No polygon geometry found.');
  process.exit(1);
}

const k = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const scale = width / ((maxLon - minLon) * k);
const height = Math.round((maxLat - minLat) * scale);
const px = (lon) => ((lon - minLon) * k * scale).toFixed(1);
const py = (lat) => ((maxLat - lat) * scale).toFixed(1);

const result = [];
for (const f of features) {
  const name = f.properties?.[nameProperty];
  if (!name) continue;
  const d = polygonsOf(f.geometry)
    .flatMap((polygon) => polygon.map((ring) => `M${ring.map(([lon, lat]) => `${px(lon)} ${py(lat)}`).join('L')}Z`))
    .join('');
  if (d) result.push({ name: String(name), d });
}

const module = `/**
 * GENERATED by scripts/geojson-to-svg.mjs. Do not edit by hand.
 * Source: ${source}${url ? ` (${url})` : ''}
 * Licence: ${license}
 */
export const IRAQ_GOVERNORATE_GEOMETRY = ${JSON.stringify(
  { viewBox: `0 0 ${width} ${height}`, attribution: { name: source, url, license }, features: result },
  null,
  2,
)};
`;
writeFileSync(out, module);
console.log(`Wrote ${result.length} features to ${out}`);
